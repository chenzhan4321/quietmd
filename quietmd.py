# 1. 数学保护扫描器
# --------------------------------------------------------------------------

class MathLocker:
    """线性扫描原文，把数学片段换成占位符，同时**跳过**代码区域。

    跳过而不是提取代码，是因为代码块本身还要交给 Markdown 正常渲染；
    我们只是不在里面找公式（免得 `echo $PATH` 变成公式）。
    """

    def __init__(self, text: str):
        import secrets
        self.s = text
        self.n = len(text)
        self.i = 0
        self.out: list[str] = []
        self.math: list[dict] = []
        self.nonce = secrets.token_hex(4)

    # -- 工具 ------------------------------------------------------------
    def _at_line_start(self) -> bool:
        return self.i == 0 or self.s[self.i - 1] == "\n"

    def _emit(self, chunk: str) -> None:
        self.out.append(chunk)

    def _lock(self, tex: str, kind: str) -> None:
        """kind: 'inline' | 'display' | 'env'"""
        idx = len(self.math)
        self.math.append({"tex": tex, "kind": kind})
        self.out.append(f"{PH_OPEN}{self.nonce}:{idx}{PH_CLOSE}")

    # -- 主循环 ----------------------------------------------------------
    def run(self) -> tuple[str, list[dict], str]:
        s, n = self.s, self.n
        while self.i < n:
            c = s[self.i]

            # (a) 围栏代码块 ``` / ~~~ ：整块原样抄过去
            if c in "`~" and self._at_line_start() and self._try_fence():
                continue

            # (b) 行内代码 `...`：原样抄过去
            if c == "`" and self._try_inline_code():
                continue

            # (c) 反斜杠开头的东西
            if c == "\\" and self.i + 1 < n:
                nxt = s[self.i + 1]
                if nxt == "[" and self._try_delim("\\[", "\\]", "display"):
                    continue
                if nxt == "(" and self._try_delim("\\(", "\\)", "inline"):
                    continue
                if nxt == "b" and self._try_env():
                    continue
                # 正文里裸写的 \eqref{...} / \ref{...}：MathJax 3 不再扫描定界符
                # 之外的引用，所以这里把它们也当成行内数学锁起来。
                if nxt in "er" and self._try_ref():
                    continue
                # \$ \\ \_ 之类转义：两个字符一起吐出，别让 $ 被后面误认
                self._emit(s[self.i:self.i + 2])
                self.i += 2
                continue

            # (d) $$ ... $$
            if c == "$" and s.startswith("$$", self.i) and self._try_dollar_display():
                continue

            # (e) $ ... $
            if c == "$" and self._try_dollar_inline():
                continue

            self._emit(c)
            self.i += 1

        return "".join(self.out), self.math, self.nonce

    # -- 各个分支 --------------------------------------------------------
    def _try_fence(self) -> bool:
        s, n = self.s, self.n
        m = re.compile(r"( {0,3})(`{3,}|~{3,})").match(s, self.i)
        if not m:
            return False
        marker = m.group(2)
        # 找闭合围栏
        pos = s.find("\n", m.end())
        if pos == -1:
            self._emit(s[self.i:])
            self.i = n
            return True
        close = re.compile(
            r"^ {0,3}" + re.escape(marker[0]) + "{" + str(len(marker)) + r",}\s*$",
            re.M,
        )
        cm = close.search(s, pos + 1)
        end = cm.end() if cm else n
        self._emit(s[self.i:end])
        self.i = end
        return True

    def _try_inline_code(self) -> bool:
        s, n = self.s, self.n
        j = self.i
        while j < n and s[j] == "`":
            j += 1
        run = j - self.i
        # 找同长度的闭合反引号串
        k = j
        while k < n:
            if s[k] == "`":
                k2 = k
                while k2 < n and s[k2] == "`":
                    k2 += 1
                if k2 - k == run:
                    self._emit(s[self.i:k2])
                    self.i = k2
                    return True
                k = k2
            else:
                k += 1
        return False  # 没闭合，当普通反引号处理

    def _try_delim(self, open_d: str, close_d: str, kind: str) -> bool:
        s = self.s
        start = self.i + len(open_d)
        end = s.find(close_d, start)
        if end == -1:
            return False
        self._lock(s[start:end], kind)
        self.i = end + len(close_d)
        return True

    def _try_env(self) -> bool:
        s = self.s
        m = ENV_RE.match(s, self.i)
        if not m:
            return False
        env = m.group(1) + m.group(2)
        # 允许同名环境嵌套（比如 align 里套 aligned），做一次配对计数
        depth = 0
        pos = self.i
        pat = re.compile(r"\\(begin|end)\{" + re.escape(env) + r"\}")
        while True:
            mm = pat.search(s, pos)
            if not mm:
                return False
            depth += 1 if mm.group(1) == "begin" else -1
            pos = mm.end()
            if depth == 0:
                break
        self._lock(s[self.i:pos], "env")
        self.i = pos
        return True

    def _try_ref(self) -> bool:
        m = re.compile(r"\\(eqref|ref)\{([^}\n]{1,120})\}").match(self.s, self.i)
        if not m:
            return False
        self._lock(m.group(0), "inline")
        self.i = m.end()
        return True

    def _try_dollar_display(self) -> bool:
        s = self.s
        start = self.i + 2
        end = s.find("$$", start)
        if end == -1:
            return False
        self._lock(s[start:end], "display")
        self.i = end + 2
        return True

    def _try_dollar_inline(self) -> bool:
        """行内 $...$ 的判定规则（沿用 pandoc 的保守做法，避免误吃货币符号）：
        - 开定界符 $ 后面不能是空白
        - 闭定界符 $ 前面不能是空白
        - 闭定界符 $ 后面不能紧跟数字（挡住 "$5 到 $10" 这种）
        - 内容不能跨空行，长度有上限
        任一条不满足，就当成一个普通的美元符号。
        """
        s, n = self.s, self.n
        start = self.i + 1
        if start >= n or s[start] in " \t\n":
            return False
        j = start
        while j < n:
            ch = s[j]
            if ch == "\\":
                j += 2
                continue
            if ch == "\n" and j + 1 < n and s[j + 1] == "\n":
                return False
            if j - start > 1200:
                return False
            if ch == "$":
                if s[j - 1] in " \t\n":
                    return False
                if j + 1 < n and s[j + 1].isdigit():
                    return False
                self._lock(s[start:j], "inline")
                self.i = j + 1
                return True
            j += 1
        return False


# --------------------------------------------------------------------------
# 1b. 目录当一本书
#
# 一堆按顺序排的 md 常常就是一份东西：教材的各章、论文的各节、整理稿的各册。
# 给一个目录就把它们接成一份来读，侧栏目录直接是全书结构。
#
# 顺序按文件名排（chapter_01…chapter_08 这类命名本来就是为排序取的）。
# 以 _ 或 . 开头的文件跳过 —— 那些通常是写作规范、证据清单之类的旁注，不是正文。
# --------------------------------------------------------------------------

def collect_dir(d: Path, exclude: tuple[str, ...] = ()) -> list[Path]:
    import fnmatch
    out = []
    for f in sorted(d.iterdir()):
        if not f.is_file() or f.suffix.lower() not in (".md", ".markdown"):
            continue
        if f.name.startswith(("_", ".")):
            continue
        if any(fnmatch.fnmatch(f.name, pat) for pat in exclude):
            continue
        out.append(f)
    return out


def _read_text(f: Path) -> str:
    raw = f.read_bytes()
    for enc in ("utf-8", "utf-8-sig", "gb18030", "latin-1"):
        try:
            return raw.decode(enc)
        except UnicodeDecodeError:
            continue
    return raw.decode("utf-8", "replace")


def join_dir(d: Path, exclude: tuple[str, ...] = ()) -> tuple[str, list[Path]]:
    """把目录里的 md 接成一份。返回 (合并后的文本, 用到的文件)。

    只拼接，不重排标题层级 —— 各章的层级是作者定的，替他改会打乱已有的结构。
    每份自己的 front matter 只保留第一份的，否则正文中间会冒出几行 --- 。
    """
    files = collect_dir(d, exclude)
    if not files:
        raise SystemExit(f"{d} 里没有 .md 文件（以 _ 或 . 开头的会跳过）。")
    parts: list[str] = []
    for i, f in enumerate(files):
        text = _read_text(f)
        meta, body = split_front_matter(text)
        parts.append(text.rstrip() if (i == 0 and meta) else body.strip())
    return "\n\n---\n\n".join(parts), files



