# 7b. 稿件体检
#
# --check 原本只回答一个问题：这条公式能不能渲染出来。但论文作者真正会踩的坑
# 有几个是渲染得好好的、却是错的 —— \eqref 指向一个不存在的 \label，MathJax
# 只会安静地显示成 ???；同一个 \label 写了两遍，编号从此就错了。
#
# 这些是纯静态的关系，公式文本已经在手上，不需要浏览器 —— 所以没装 Chrome 的
# 机器也能做这部分检查。
# --------------------------------------------------------------------------

LABEL_RE = re.compile(r"\\label\{([^}\n]{1,120})\}")
REF_RE = re.compile(r"\\(?:eq)?ref\{([^}\n]{1,120})\}")
# \newcommand{\foo} / \newcommand\foo / \renewcommand / \def / \DeclareMathOperator
DEF_RE = re.compile(
    r"\\(?:re)?newcommand\s*\{?\\([A-Za-z@]+)\}?"
    r"|\\def\s*\\([A-Za-z@]+)"
    r"|\\DeclareMathOperator\*?\s*\{?\\([A-Za-z@]+)\}?"
)


def audit_manuscript(math: list[dict]) -> list[tuple[str, str]]:
    """交叉比对标签与宏，返回 [(类别, 说明)]。类别用于分类打印。"""
    blob = "\n".join(m["tex"] for m in math)

    labels: dict[str, int] = {}
    for name in LABEL_RE.findall(blob):
        labels[name] = labels.get(name, 0) + 1
    refs: dict[str, int] = {}
    for name in REF_RE.findall(blob):
        refs[name] = refs.get(name, 0) + 1

    defs: dict[str, int] = {}
    for groups in DEF_RE.findall(blob):
        name = next(g for g in groups if g)
        defs[name] = defs.get(name, 0) + 1

    found: list[tuple[str, str]] = []

    for name in sorted(r for r in refs if r not in labels):
        found.append(("dangling-ref", f"\\eqref{{{name}}} → 找不到对应的 \\label"))
    for name, n in sorted(labels.items()):
        if n > 1:
            found.append(("duplicate-label", f"\\label{{{name}}} 出现了 {n} 次，编号会错"))
    for name, n_def in sorted(defs.items()):
        # 定义语句本身也含一次 \name，所以出现次数要减掉定义数才是真正的使用
        uses = len(re.findall(r"\\" + re.escape(name) + r"(?![A-Za-z])", blob)) - n_def
        if uses <= 0:
            found.append(("unused-macro", f"\\{name} 定义了但从未使用"))
        if n_def > 1:
            found.append(("redefined-macro", f"\\{name} 被定义了 {n_def} 次"))
    return found


AUDIT_LABELS = {
    "en": {"dangling-ref": "dangling reference", "duplicate-label": "duplicate label",
           "unused-macro": "unused macro", "redefined-macro": "macro redefined"},
    "zh": {"dangling-ref": "悬空引用", "duplicate-label": "重复的 label",
           "unused-macro": "未使用的宏", "redefined-macro": "重复定义的宏"},
}

CHROME_CANDIDATES = [
    # macOS
    "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
    "/Applications/Google Chrome Beta.app/Contents/MacOS/Google Chrome Beta",
    "/Applications/Chromium.app/Contents/MacOS/Chromium",
    "/Applications/Brave Browser.app/Contents/MacOS/Brave Browser",
    "/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge",
    # Linux 上常见的安装位置
    "/usr/bin/google-chrome",
    "/usr/bin/google-chrome-stable",
    "/usr/bin/chromium",
    "/usr/bin/chromium-browser",
    "/snap/bin/chromium",
]


def find_chrome() -> str | None:
    """找一个 Chromium 系浏览器给 --check 用。

    顺序：环境变量 CHROME → 常见安装路径 → PATH。最后这步是为 CI 准备的，
    那里的浏览器往往装在临时目录里，只能靠 PATH 找到。
    """
    import shutil

    env = os.environ.get("CHROME") or os.environ.get("CHROME_PATH")
    if env and Path(env).is_file():
        return env
    for c in CHROME_CANDIDATES:
        if Path(c).is_file():
            return c
    for name in ("google-chrome", "google-chrome-stable", "chromium",
                 "chromium-browser", "chrome"):
        found = shutil.which(name)
        if found:
            return found
    return None


def check(md_path: Path, mathjax_js: str, joined: str | None = None) -> int:
    """稿件体检 + 渲染检查。

    两段独立：
      1. 静态体检 —— 标签与宏的交叉比对，纯文本分析，不需要浏览器。
      2. 渲染检查 —— 用无头浏览器真跑一遍 MathJax，逐条核对有没有排出来。
    没装 Chrome 时第 2 段跳过，第 1 段照做。
    退出码 0 表示两段都干净，可以直接进脚本。
    """
    import subprocess
    import tempfile

    zh = cli_lang() == "zh"
    text = joined if joined is not None else _read_text(md_path)
    _, math, _ = MathLocker(split_front_matter(text)[1]).run()

    problems = 0

    # ---- 1. 静态体检 --------------------------------------------------
    issues = audit_manuscript(math)
    if issues:
        problems += len(issues)
        names = AUDIT_LABELS["zh" if zh else "en"]
        for kind, msg in issues:
            print(f"  [{names[kind]}] {msg}")

    # ---- 2. 渲染检查 --------------------------------------------------
    chrome = find_chrome()
    if not chrome:
        print(f"{md_path.name}：{len(math)} 处公式；"
              "没找到 Chrome/Chromium，跳过渲染检查（静态体检已完成）。" if zh else
              f"{md_path.name}: {len(math)} formulas; no Chrome/Chromium found, "
              "skipped the render check (static audit done).", file=sys.stderr)
        return 1 if problems else 0

    page = build_html(md_path, mathjax_js, watch=False, text=joined)
    with tempfile.TemporaryDirectory() as td:
        tmp = Path(td) / "check.html"
        tmp.write_text(page, encoding="utf-8")
        try:
            out = subprocess.run(
                [chrome, "--headless=new", "--disable-gpu", "--no-sandbox",
                 "--window-size=1400,900", "--virtual-time-budget=45000",
                 "--dump-dom", tmp.as_uri()],
                capture_output=True, text=True, timeout=300,
            ).stdout
        except subprocess.TimeoutExpired:
            print("渲染超时。" if zh else "Rendering timed out.", file=sys.stderr)
            return 2

    m = re.search(r'data-math-total="(\d+)" data-math-failed="(\d+)" data-math-warn="(\d+)"', out)
    if not m:
        print("没能读到渲染结果（页面可能没跑完 MathJax）。" if zh else
              "Couldn't read the render result (MathJax may not have finished).",
              file=sys.stderr)
        return 2
    total, failed, warned = (int(m.group(i)) for i in (1, 2, 3))
    problems += failed + warned

    def collect(cls):
        return [" ".join(html.unescape(x).split()) for x in
                re.findall(r'class="mjx-\w+ ' + cls + r'" data-tex="([^"]*)"', out)]

    label = md_path.name + ("/" if md_path.is_dir() else "")
    if zh:
        print(f"{label}：{total} 处公式，{failed} 处排不出来，{warned} 处含不认识的命令")
        labels = ("排不出来", "不认识的命令")
    else:
        print(f"{label}: {total} formulas, {failed} won't render, "
              f"{warned} with unknown commands")
        labels = ("won't render", "unknown command")
    for label, items in zip(labels, (collect("mjx-failed"), collect("mjx-warn"))):
        for i, tex in enumerate(items, 1):
            print(f"  [{label}] {i}. {tex[:110]}{'…' if len(tex) > 110 else ''}")
    if not problems:
        print("  全部正常。" if zh else "  All good.")
    return 1 if problems else 0


def main() -> int:
    ap = argparse.ArgumentParser(
        prog="quietmd",
        description="A quiet Markdown reader for documents with math "
                    "/ 安静地读带公式的 Markdown")
    ap.add_argument("file", help="a .md file, or a directory of them to read as one")
    ap.add_argument("-w", "--watch", action="store_true", help="实时预览：存盘即刷新")
    ap.add_argument("-o", "--out", help="输出 HTML 路径（不打开浏览器）")
    ap.add_argument("-p", "--port", type=int, default=0, help="--watch 的端口（默认随机）")
    ap.add_argument("--no-open", action="store_true", help="不要自动打开浏览器")
    ap.add_argument("-c", "--check", action="store_true",
                    help="只检查：真跑一遍 MathJax，列出渲染不出来的公式（全部正常则退出码 0）")
    ap.add_argument("-s", "--style", default="paper", choices=list(STYLES),
                    help="initial typographic style: "
                         + ", ".join(f"{k}={v['en']}" for k, v in STYLES.items())
                         + " (press s in the page to cycle)")
    ap.add_argument("-V", "--version", action="version",
                    version=f"quietmd {__version__}")
    ap.add_argument("--exclude", action="append", default=[], metavar="GLOB",
                    help="when reading a directory, skip files matching this "
                         "(repeatable, e.g. --exclude 'full_*.md')")
    ap.add_argument("--lang", default="en", choices=["en", "zh"],
                    help="initial interface language (a button in the page switches it)")
    args = ap.parse_args()

    md_path = Path(args.file).expanduser().resolve()
    if not md_path.exists():
        print(f"找不到：{md_path}" if cli_lang() == "zh" else f"Not found: {md_path}",
              file=sys.stderr)
        return 1

    joined: str | None = None
    if md_path.is_dir():
        joined, files = join_dir(md_path, tuple(args.exclude))
        zh = cli_lang() == "zh"
        # 把接了哪些文件列全 —— 目录里混进产物或旁注是常事，
        # 只有看得见清单才发现得了（比如一份合并稿把全书又算了一遍）
        head = f"{md_path.name}/：按文件名接了 {len(files)} 份" if zh else \
               f"{md_path.name}/: joined {len(files)} files in name order"
        print(head, file=sys.stderr)
        for f in files:
            print(f"  {f.name}", file=sys.stderr)
    mathjax_js = ensure_mathjax().read_text(encoding="utf-8")

    if args.check:
        return check(md_path, mathjax_js, joined)

    if args.watch:
        serve(md_path, mathjax_js, args.port, open_browser=not args.no_open,
              style=args.style, lang=args.lang, excl=tuple(args.exclude))
        return 0

    page = build_html(md_path, mathjax_js, watch=False, style=args.style,
                      lang=args.lang, text=joined)
    if args.out:
        out = Path(args.out).expanduser().resolve()
    else:
        out = default_out(md_path)
    out.write_text(page, encoding="utf-8")
    print(f"{out}  ({out.stat().st_size/1024/1024:.1f} MB, 自包含)")
    if not args.out and not args.no_open:
        webbrowser.open(out.as_uri())
    return 0


if __name__ == "__main__":
    sys.exit(main())
