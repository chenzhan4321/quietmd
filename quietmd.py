# 3. 资源内嵌（图片 / 相对链接）
# --------------------------------------------------------------------------

def inline_assets(body: str, base_dir: Path) -> tuple[str, int]:
    """把本地图片编成 base64 塞进 HTML，让产物真的是「一个文件」。

    超出预算的图片改成 file:// 绝对路径 —— 那样页面在本机还能看，
    但发给别人就断了。返回被跳过的张数，由调用方告诉用户，不闷着。
    """
    budget = [IMG_INLINE_BUDGET]
    skipped = [0]

    def fix_src(m):
        pre, url, post = m.group(1), m.group(2), m.group(3)
        if re.match(r"^(https?:|data:|#|mailto:|file:)", url):
            return m.group(0)
        p = (base_dir / url.split("#")[0].split("?")[0]).resolve()
        if not p.is_file():
            return m.group(0)
        data = p.read_bytes()
        if len(data) <= budget[0]:
            budget[0] -= len(data)
            mime = mimetypes.guess_type(p.name)[0] or "application/octet-stream"
            b64 = base64.b64encode(data).decode()
            return f'{pre}data:{mime};base64,{b64}{post}'
        return f'{pre}file://{p}{post}'

    body = re.sub(r'(<img[^>]*\ssrc=")([^"]+)(")', fix_src, body)

    def fix_href(m):
        pre, url, post = m.group(1), m.group(2), m.group(3)
        if re.match(r"^(https?:|data:|#|mailto:|file:)", url):
            return m.group(0)
        p = (base_dir / url).resolve()
        return f'{pre}file://{p}{post}' if p.exists() else m.group(0)

    return re.sub(r'(<a[^>]*\shref=")([^"]+)(")', fix_href, body), skipped[0]


